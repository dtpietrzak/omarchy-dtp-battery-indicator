const assert = require("assert")
const fs = require("fs")
const path = require("path")

const Battery = require("../Battery.js")
const root = path.join(__dirname, "..")
const read = name => fs.readFileSync(path.join(root, name), "utf8")

const at22 = Battery.metrics(22, 1)
assert.strictEqual(at22.bodyHeight, 10, "2px shorter than the 12px body")
assert.ok(at22.bodyHeight < 22 - 4, "battery fits in the bar")
assert.strictEqual(at22.bodyWidth, 20, "3px thinner than the 23px body")
assert.strictEqual(at22.tipWidth, 3, "stud is 1px longer")
assert.ok(at22.bodyWidth > at22.bodyHeight, "battery is horizontal")
assert.ok(at22.tipWidth - at22.stroke >= 2, "stud sticks out to the left")
assert.ok(at22.width > at22.bodyWidth - at22.stroke, "tip adds width on the left")
assert.ok(at22.fontSize >= 9 && at22.fontSize < at22.bodyHeight, "number fills the body")

const at26 = Battery.metrics(26, 2)
assert.strictEqual(at26.bodyHeight * 2, Math.round(at26.bodyHeight * 2))
assert.strictEqual(at26.stroke * 2, Math.round(at26.stroke * 2))
assert.ok(at26.bodyHeight > at22.bodyHeight)

assert.strictEqual(Battery.level(0.984), 98)
assert.strictEqual(Battery.level(1), 100)
assert.strictEqual(Battery.level(-1), 0)
assert.strictEqual(Battery.level(2), 100)
assert.strictEqual(Battery.level(NaN), 0)

assert.strictEqual(Battery.plain("98"), "98")
assert.strictEqual(Battery.plain("9<img>"), "9img")
assert.ok(!Battery.plain("98").includes("%"))

assert.strictEqual(Battery.isLow(0.15, true), true)
assert.strictEqual(Battery.isLow(0.16, true), false)
assert.strictEqual(Battery.isLow(0.1, false), false)

const strings = JSON.parse(read("i18n/en.json"))
for (const key of ["battery.level", "battery.charging", "battery.full", "battery.holding"]) {
  assert.strictEqual(typeof strings[key], "string", key)
  assert.ok(strings[key].includes("%1"), key + " takes the number")
  assert.ok(!strings[key].replace("%1", "").includes("%"), key + " has no percent sign")
  assert.ok(!/[<>]/.test(strings[key]), key + " has no markup")
}

const panel = read("Panel.qml")
const mark = read("BatteryMark.qml")
assert.ok(panel.includes("BatteryMark"))
assert.ok(panel.includes("verticalCenterOffset: 0"), "the bar mark sits centered")
assert.ok(!/\+\s*"%"/.test(panel), "the bar does not append a percent sign")
assert.ok(mark.includes("textFormat: Text.PlainText"))
assert.ok(mark.includes("color: mark.fillColor"), "the number matches the outline")
assert.ok(mark.includes("Font.Black"), "the number is heavy")
assert.ok(mark.includes("verticalCenterOffset:"), "the number is centered in the body")
assert.ok(/verticalCenterOffset:[\s\S]*- 1/.test(mark), "native digits are pulled up into the body")
assert.ok(mark.includes("mark.charge"), "the inside tracks the charge")
assert.ok(mark.includes("parent.width - mark.shape.stroke - width"), "the fill sits on the right, so the empty part is on the left")
assert.ok(/rgba\(fillColor\.r, fillColor\.g, fillColor\.b, 0\.75\)/.test(mark), "the outline is 75% opaque")
assert.ok(/rgba\(fillColor\.r, fillColor\.g, fillColor\.b, 0\.35\)/.test(mark), "the inside is 35% opaque")
assert.ok(!panel.includes("Commons.Color.accent"), "the number is not the accent color")
assert.ok(mark.includes("border.width: mark.shape.stroke"), "the shell is an outline")
assert.ok(mark.includes("topLeftRadius"))
assert.ok(/x:\s*0/.test(mark), "tip starts at the left")
assert.ok(mark.includes("parent.height * 0.64"), "charging bolt scales to the battery body")
assert.ok(!mark.includes('strokeColor: "#202020"'), "charging bolt has no jagged dark outline")
assert.ok(mark.includes("chargeBolt.width * 0.62"), "charging bolt uses the refined glyph geometry")
assert.ok(mark.includes("fillColor: mark.boltColor"), "charging bolt uses the bolt color")
assert.ok(mark.includes("Battery.snap(Math.min"), "charging bolt bounds land on device pixels")
assert.ok(mark.includes("parent.height + mark.shape.stroke * 2"), "charging bolt overlaps the battery shell")
assert.ok(mark.includes("mark.charging || mark.holding ? -Style.space(1) : 0"), "charging and holding numbers shift left by 1px")
assert.ok(mark.includes("x: parent.width - width + Style.space(4)"), "charging bolt sits 4px past the battery's right edge")
assert.ok(mark.includes("z: 1"), "charging bolt paints above the battery shell")
assert.ok(mark.includes("property bool holding: false"), "battery mark supports the holding state")
assert.ok(mark.includes("visible: mark.showBolt"), "bolt is shown while charging or holding")
assert.ok(mark.includes("fillColor: mark.boltColor"), "holding bolt can use a distinct color")
assert.ok(panel.includes("holding: root.chargeThresholdActive"), "holding state reaches the battery marks")
assert.ok(mark.includes("outlineColor: holding ? fillColor"), "holding shell matches the battery fill")
assert.ok(mark.includes("interiorColor: holding ? fillColor"), "holding interior matches the battery fill")
assert.ok(panel.includes('strings.t("battery.level")'))
assert.ok(panel.includes('strings.t("battery.charging")'))
assert.ok(panel.includes('strings.t("battery.full")'))
assert.ok(panel.includes('strings.t("battery.holding")'))
assert.ok(panel.includes("omarchy-powerprofiles-set"), "click still opens the power panel")

console.log("ok")
